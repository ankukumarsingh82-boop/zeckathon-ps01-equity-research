def _tbl(rows, widths, fs=6.9, hl_row=None, left_cols=1):
    t = Table(rows, colWidths=widths, hAlign="LEFT")
    st = [("FONT", (0, 0), (-1, -1), "Helvetica", fs), ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", fs),
          ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#dfe8f2")), ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
          ("ALIGN", (left_cols, 0), (-1, -1), "RIGHT"), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
          ("TOPPADDING", (0, 0), (-1, -1), 1), ("BOTTOMPADDING", (0, 0), (-1, -1), 1)]
    if hl_row is not None:
        st.append(("BACKGROUND", (0, hl_row), (-1, hl_row), colors.HexColor("#fff4cc")))
    t.setStyle(TableStyle(st))
    return t


def _in_ci(res: dict, w: str) -> str:
    kr, bu = res["tabs"]["ke_regression"], res["tabs"]["ke_bottom_up"]
    lo, hi = kr.loc[w, "blume_ci95_low"], kr.loc[w, "blume_ci95_high"]
    ok = bu[(bu["beta_used"] >= lo) & (bu["beta_used"] <= hi)]
    if ok.empty:
        return "none"
    return "; ".join(f"'{i}' {r.beta_used:.2f} -> TP INR {r[w + '_tp']:.0f}" for i, r in ok.iterrows()) + f" (CMP {kr.loc[w, 'cmp']:.0f})"


