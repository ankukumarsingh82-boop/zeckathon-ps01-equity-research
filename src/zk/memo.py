def doc_for(path: Path, title: str) -> SimpleDocTemplate:
    return SimpleDocTemplate(str(path), pagesize=A4, leftMargin=12*mm, rightMargin=12*mm, topMargin=10*mm, bottomMargin=10*mm,
                             title=title, author="Zeckathon PS-01 team", invariant=1)


def build_memo(res: dict, path: Path | None = None) -> Path:
    path = path or OUT / "IC_memo.pdf"
    doc_for(path, "Zeckathon PS-01 IC memo").build(memo_story(res))
    return path
